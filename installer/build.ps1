# Builds the twoncut setup exe: zips the panel files, draws the icon and compiles Installer.cs.
# Usage: powershell -ExecutionPolicy Bypass -File installer\build.ps1
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$panel = Join-Path (Split-Path -Parent $here) 'extension'
$out = Join-Path (Split-Path -Parent $here) 'dist'
$build = Join-Path $here 'build'
New-Item -ItemType Directory -Force $build, $out | Out-Null

Add-Type -AssemblyName System.IO.Compression, System.IO.Compression.FileSystem, System.Drawing

# 0) The extension manifest is the single source of truth for the version
$manifest = Get-Content (Join-Path $panel 'CSXS\manifest.xml') -Raw
if ($manifest -notmatch 'ExtensionBundleVersion="(\d+\.\d+\.\d+)"') { throw "Version not found in manifest.xml" }
$version = $Matches[1]
@"
// Generated by build.ps1 - do not edit.
using System.Reflection;
[assembly: AssemblyVersion("$version.0")]
[assembly: AssemblyFileVersion("$version.0")]
[assembly: AssemblyInformationalVersion("$version")]
namespace Twoncut { static class BuildInfo { public const string Version = "$version"; } }
"@ | Set-Content (Join-Path $build 'BuildInfo.cs') -Encoding UTF8

# 1) Zip the panel files (zip entries use / as separator)
$zipPath = Join-Path $build 'payload.zip'
if (Test-Path $zipPath) { Remove-Item $zipPath }
$zip = [System.IO.Compression.ZipFile]::Open($zipPath, 'Create')
try {
    foreach ($item in 'CSXS', 'css', 'js', 'jsx', 'index.html') {
        $src = Join-Path $panel $item
        $files = if (Test-Path $src -PathType Container) { Get-ChildItem $src -Recurse -File } else { Get-Item $src }
        foreach ($f in $files) {
            $rel = $f.FullName.Substring($panel.Length + 1).Replace('\', '/')
            [System.IO.Compression.ZipFileExtensions]::CreateEntryFromFile($zip, $f.FullName, $rel) | Out-Null
        }
    }
} finally { $zip.Dispose() }

# 2) Icon: white wave bars on a violet-blue rounded square (.ico with PNG frames)
$icoPath = Join-Path $build 'twoncut.ico'
$sizes = 16, 24, 32, 48, 64, 128, 256
$pngs = foreach ($s in $sizes) {
    $bmp = New-Object System.Drawing.Bitmap $s, $s
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.SmoothingMode = 'AntiAlias'
    $rect = New-Object System.Drawing.RectangleF 0, 0, $s, $s
    $r = $s * 0.22; $d = $r * 2
    $path = New-Object System.Drawing.Drawing2D.GraphicsPath
    $path.AddArc(0, 0, $d, $d, 180, 90); $path.AddArc($s - $d - 0.5, 0, $d, $d, 270, 90)
    $path.AddArc($s - $d - 0.5, $s - $d - 0.5, $d, $d, 0, 90); $path.AddArc(0, $s - $d - 0.5, $d, $d, 90, 90); $path.CloseFigure()
    $brush = New-Object System.Drawing.Drawing2D.LinearGradientBrush $rect, ([System.Drawing.Color]::FromArgb(139, 92, 246)), ([System.Drawing.Color]::FromArgb(96, 165, 250)), 45
    $g.FillPath($brush, $path)
    $white = New-Object System.Drawing.SolidBrush ([System.Drawing.Color]::White)
    $heights = 0.30, 0.58, 0.40, 0.70, 0.36
    $bw = [Math]::Max(1, $s * 0.085); $gap = $s * 0.065
    $total = 5 * $bw + 4 * $gap; $x = ($s - $total) / 2
    foreach ($h in $heights) {
        $bh = $s * $h
        $g.FillRectangle($white, [float]$x, [float](($s - $bh) / 2), [float]$bw, [float]$bh)
        $x += $bw + $gap
    }
    $g.Dispose()
    $ms = New-Object System.IO.MemoryStream
    $bmp.Save($ms, [System.Drawing.Imaging.ImageFormat]::Png); $bmp.Dispose()
    , $ms.ToArray()
}
$fs = [System.IO.File]::Create($icoPath)
$bw2 = New-Object System.IO.BinaryWriter $fs
$bw2.Write([UInt16]0); $bw2.Write([UInt16]1); $bw2.Write([UInt16]$sizes.Count)
$offset = 6 + 16 * $sizes.Count
for ($i = 0; $i -lt $sizes.Count; $i++) {
    $s = $sizes[$i]; $len = $pngs[$i].Length
    $bw2.Write([byte]($(if ($s -ge 256) { 0 } else { $s }))); $bw2.Write([byte]($(if ($s -ge 256) { 0 } else { $s })))
    $bw2.Write([byte]0); $bw2.Write([byte]0); $bw2.Write([UInt16]1); $bw2.Write([UInt16]32)
    $bw2.Write([UInt32]$len); $bw2.Write([UInt32]$offset); $offset += $len
}
foreach ($p in $pngs) { $bw2.Write($p) }
$bw2.Close()

# 3) Compile
$fw = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319'
$csc = Join-Path $fw 'csc.exe'
$exe = Join-Path $out 'twoncut-setup.exe'
& $csc /nologo /target:winexe /optimize+ /codepage:65001 "/out:$exe" `
    "/win32icon:$icoPath" "/win32manifest:$(Join-Path $here 'app.manifest')" `
    "/resource:$zipPath,payload.zip" `
    /r:System.dll /r:System.Drawing.dll /r:System.Windows.Forms.dll `
    "/r:$fw\System.IO.Compression.dll" `
    (Join-Path $here 'Installer.cs') (Join-Path $build 'BuildInfo.cs')
if ($LASTEXITCODE -ne 0) { throw "Build failed" }
Write-Host "Built v$($version): $exe ($([Math]::Round((Get-Item $exe).Length / 1KB)) KB)"
